import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const base=process.argv[2] || 'http://127.0.0.1:4218';
const output='.sms-audit.local/phone-review-validation';
mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
let checks=0;
try {
  for (const width of [1440,375,320]) {
    const context=await browser.newContext({viewport:{width,height:950}});
    const user={id:'phone-review-fixture',name:'Import fixture',email:'fixture@example.invalid',role:'user',email_verified:true};
    await context.addInitScript(user=>{
      localStorage.setItem('auth_user',JSON.stringify(user));localStorage.setItem('auth_token','fixture-only');
      localStorage.setItem('auth_token_issued',String(Date.now()));localStorage.setItem('ieosuia_cookie_consent','{}');
    },user);
    const imports=[],errors=[];
    let failImport=true;
    await context.route('**/api/**',async route=>{
      const path=new URL(route.request().url()).pathname;
      let body={success:true};
      if(path.endsWith('/auth/user'))body={...body,user};
      else if(path.endsWith('/notifications'))body={...body,notifications:[],unread_count:0,has_more:false};
      else if(path.endsWith('/wallet'))body={...body,wallet:{balance:35,reserved:0,sms_credits:100}};
      else if(path.endsWith('/contact-groups'))body={...body,total_contacts:0,groups:[{id:'1',name:'Destination',contact_count:0}]};
      else if(path.endsWith('/contacts/import')) {
        imports.push(route.request().postData());
        if(failImport)return route.fulfill({status:400,json:{success:false,error:'Fixture validation failed. Review and try again.'}});
        body={...body,imported:3,duplicates:1,failed:0,existing_added_to_group:0,corrected:3,rejected:1};
      } else if(path.endsWith('/contacts'))body={...body,data:[],meta:{current_page:1,total:0,last_page:1,opted_out_total:0}};
      await route.fulfill({json:body});
    });
    const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
    await page.goto(base+'/contacts');
    await page.getByRole('button',{name:'Destination',exact:true}).click();
    await page.getByRole('heading',{name:'Destination',exact:true}).waitFor();
    await page.getByRole('button',{name:'Import',exact:true}).click();
    const dialog=page.getByRole('dialog');
    const upload=async text=>{
      await dialog.locator('input[type=file]').setInputFiles({name:'contacts.csv',mimeType:'text/csv',buffer:Buffer.from(text)});
      await dialog.getByRole('button',{name:'Continue',exact:true}).click();
    };
    await upload('Name,Phone\nValid,0821234567\nMissing zero,821234567\nManual,short\nExtra prefix,270821234568\nUnknown,broken\n');
    const importButton=()=>dialog.getByRole('button',{name:/^Import \d+ Contacts to Destination$/});
    assert.equal(await importButton().isDisabled(),true);checks++;
    assert.equal(await dialog.getByLabel('Proposed correction for row 3',{exact:true}).inputValue(),'0821234567');checks++;
    assert.equal(await dialog.getByLabel('Proposed correction for row 5',{exact:true}).inputValue(),'0821234568');checks++;
    assert.equal(await dialog.getByRole('button',{name:'Accept correction for row 4',exact:true}).isDisabled(),true);checks++;
    await dialog.getByRole('checkbox',{name:'Select row 3',exact:true}).click();
    await dialog.getByRole('checkbox',{name:'Select row 5',exact:true}).click();
    await dialog.getByRole('button',{name:'Accept selected (2)',exact:true}).click();
    assert.match(await dialog.innerText(),/2 awaiting your choice · 2 corrections accepted/);checks++;
    await dialog.getByRole('button',{name:'Reject row 6',exact:true}).click();
    await dialog.getByLabel('Proposed correction for row 4',{exact:true}).fill('0821234569');
    await dialog.getByRole('button',{name:'Accept correction for row 4',exact:true}).click();
    assert.equal(await importButton().isEnabled(),true);checks++;
    await dialog.getByLabel('Proposed correction for row 4',{exact:true}).fill('082');
    assert.equal(await importButton().isDisabled(),true);checks++;
    await dialog.getByLabel('Proposed correction for row 4',{exact:true}).fill('27821234569');
    await dialog.getByRole('button',{name:'Accept correction for row 4',exact:true}).click();
    await dialog.getByRole('button',{name:'Reject selected (2)',exact:true}).click();
    assert.match(await dialog.innerText(),/0 awaiting your choice · 1 corrections accepted · 3 rows rejected/);checks++;
    await dialog.getByRole('button',{name:'Accept all proposals',exact:true}).click();
    assert.match(await dialog.innerText(),/0 awaiting your choice · 3 corrections accepted · 1 rows rejected/);checks++;
    assert.match(await dialog.innerText(),/Matches another number in this file/);checks++;
    await page.screenshot({path:`${output}/review-${width}.png`,fullPage:true});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));checks++;
    assert.ok(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1));checks++;
    await importButton().click();
    await dialog.getByRole('region',{name:'Phone number reconstruction'}).waitFor();
    assert.equal(await dialog.getByLabel('Proposed correction for row 4',{exact:true}).inputValue(),'27821234569');checks++;
    assert.match(await dialog.innerText(),/3 corrections accepted · 1 rows rejected/);checks++;
    failImport=false;
    await importButton().click();
    await dialog.getByRole('button',{name:'Done',exact:true}).waitFor();
    assert.match(imports[0],/name="phone_review_version"\r?\n\r?\n1/);checks++;
    assert.match(imports[0],/"row":3,"action":"accept","original":"821234567","value":"0821234567"/);checks++;
    assert.match(imports[0],/"Missing zero","821234567"/);checks++;
    assert.match(await dialog.innerText(),/3 number corrections approved; 1 rows excluded by your choice/);checks++;
    await dialog.getByRole('button',{name:'Done',exact:true}).click();
    await page.getByRole('button',{name:'Import',exact:true}).click();
    await dialog.locator('input[type=file]').setInputFiles({name:'no-headings.csv',mimeType:'text/csv',buffer:Buffer.from('821234570\n27821234571\n')});
    assert.equal(await dialog.getByRole('checkbox',{name:'First row contains column headings',exact:true}).isChecked(),false);checks++;
    assert.match(await dialog.innerText(),/First contact phone: 821234570/);checks++;
    await dialog.getByRole('button',{name:'Continue',exact:true}).click();
    assert.equal(await dialog.getByLabel('Proposed correction for row 1',{exact:true}).inputValue(),'0821234570');checks++;
    await dialog.getByRole('button',{name:'Accept all proposals',exact:true}).click();
    assert.match(await importButton().innerText(),/Import 2 Contacts/);checks++;
    await importButton().click();await dialog.getByRole('button',{name:'Done',exact:true}).waitFor();
    assert.match(imports.at(-1),/"Column 1"\r?\n"821234570"\r?\n"27821234571"/);checks++;
    assert.match(imports.at(-1),/"row":2,"action":"accept","original":"821234570"/);checks++;
    await dialog.getByRole('button',{name:'Done',exact:true}).click();
    await page.getByRole('button',{name:'Import',exact:true}).click();
    await upload('Phone\n'+Array.from({length:27},(_,i)=>String(820000000+i)).join('\n'));
    await dialog.getByRole('button',{name:'Next rows',exact:true}).click();
    await dialog.getByLabel('Proposed correction for row 28',{exact:true}).waitFor();
    await dialog.getByRole('checkbox',{name:'Select all 27 flagged rows',exact:true}).click();
    await dialog.getByRole('button',{name:'Accept selected (27)',exact:true}).click();
    assert.match(await dialog.innerText(),/0 awaiting your choice · 27 corrections accepted/);checks++;
    assert.match(await importButton().innerText(),/Import 27 Contacts/);checks++;
    await dialog.getByRole('button',{name:'Back',exact:true}).click();
    await dialog.getByRole('button',{name:'Continue',exact:true}).click();
    assert.match(await dialog.innerText(),/27 awaiting your choice · 0 corrections accepted/);checks++;
    assert.deepEqual(errors,[]);checks++;
    await context.close();
  }
  console.log(`${checks} phone reconstruction browser checks passed at desktop, 375px and 320px. All API requests mocked; no production writes.`);
} finally { await browser.close(); }
